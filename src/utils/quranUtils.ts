export const arabicToEnglishDigits = (str: string): string => {
  const map: Record<string, string> = {
    '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
    '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9'
  };
  return str.replace(/[٠-٩]/g, (d) => map[d]);
};

export const getAyahAudioUrl = (surahName: string, ayahNumber: string): string | null => {
  const surahNum = SURAH_NAME_TO_NUMBER[surahName];
  if (!surahNum) return null;

  // Handle ranges by taking the first ayah
  const englishAyah = arabicToEnglishDigits(ayahNumber);
  const firstAyahMatch = englishAyah.match(/^\d+/);
  if (!firstAyahMatch) return null;

  const ayahNum = firstAyahMatch[0];
  
  // Using Alquran.cloud API for a specific reciter (Alafasy)
  return `https://cdn.islamic.network/quran/audio/128/ar.alafasy/${globalAyahNumber(surahNum, parseInt(ayahNum))}.mp3`;
};

