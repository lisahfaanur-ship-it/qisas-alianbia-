/**
 * دالة مساعدة ذكية لاسترجاع أو بناء آيات التدبر لأي قصة نبي
 * - إذا كان للنبي آيات مخصصة في البنك المعتمد أعلاه تسترجع فوراً.
 * - يتم استخراج أي آيات مذكورة في فصول القصة `associatedAyah` ودمجها مع صياغة تفسيرية مبسطة مناسبة.
 */
export function getTadabburVersesForProphet(
  prophet: ProphetStory,
  selectedAge: AgeGroup = '8-10'
): TadabburVerse[] {
  const curated = curatedTadabburVersesByProphet[prophet.id] || [];

  // نجمع أيضاً الآيات من فصول القصة لنفس الفئة العمرية أو الفئات الأخرى لضمان الغنى
  const collectedFromChapters: TadabburVerse[] = [];
  const activeAgeChapters = prophet.ageVariants[selectedAge]?.chapters || [];

  activeAgeChapters.forEach((chap, idx) => {
    if (chap.associatedAyah && chap.associatedAyah.text) {
      // نتأكد ألا تكون مكررة مع الموجود
      const existsInCurated = curated.some(
        c => c.surah === chap.associatedAyah!.surah && (c.ayahNumber.includes(chap.associatedAyah!.ayahNumber) || chap.associatedAyah!.ayahNumber.includes(c.ayahNumber))
      );
      const existsInCollected = collectedFromChapters.some(
        c => c.surah === chap.associatedAyah!.surah && c.ayahNumber === chap.associatedAyah!.ayahNumber
      );

      if (!existsInCurated && !existsInCollected) {
        const ayah = chap.associatedAyah;
        collectedFromChapters.push({
          id: `${prophet.id}-chap-${idx + 1}`,
          surah: ayah.surah,
          ayahNumber: ayah.ayahNumber,
          text: ayah.text,
          theme: `شاهد من فصل: ${chap.title}`,
          chapterTitle: chap.title,
          audioUrl: ayah.audioUrl,
          tafsirSource: 'التفسير الميسر وتفسير السعدي (تيسير الكريم الرحمن)',
          ageExplanations: {
            '5-7': {
              summary: ayah.explanation || `آية كريمة تخبرنا عن رعاية الله لنبيه ${prophet.name}، وتدعونا لحب الله وطاعته.`,
              actionPoint: `تذكر دائماً أن الله كريم رحيم يسمع دعاءك ويراك.`,
              discussionQuestion: `ما أجمل كلمة أعجبتك في هذه الآية يا بطل؟`
            },
            '8-10': {
              summary: ayah.explanation ? `${ayah.explanation}، وفيها بيان لحكمة الله وتأييده لأنبيائه عليهم السلام.` : `توضح الآية الكريمة حدثاً مباركاً من قصة نبي الله ${prophet.name}، وضرورة التمسك بالحق والعمل الصالح.`,
              actionPoint: `اقتدِ بنبي الله ${prophet.name} في حسن خلقه وإيمانه الصادق.`,
              discussionQuestion: `كيف ترتبط هذه الآية بأحداث الفصل الذي قرأته؟`
            },
            '11-13': {
              summary: ayah.explanation ? `${ayah.explanation}. ويستفاد منها إرساء أسس التوحيد واليقين في مواجهة التحديات.` : `دلالة الآية تؤكد سنن الله في نصرة رسله، وأهمية أخذ العبرة والدروس الإيمانية العميقة في بناء الشخصية المسلمة.`,
              actionPoint: `اربط فهمك للآية بسلوكك اليومي من خلال الصدق في المعاملة والتوكل على الله.`,
              discussionQuestion: `ما البعد الإيماني والتربوي الذي تلمسه في هذا التوجيه القرآني الكريم؟`,
              deeperTafsir: `مأخوذة من سياق سورة ${ayah.surah} في تقرير دلائل صدق النبوة والاعتبار بسير الأنبياء والمرسلين.`
            }
          }
        });
      }
    }
  });

  // ندمج الآيات المخصصة أولاً ثم الآيات المستخرجة
  const allVerses = [...curated, ...collectedFromChapters];

  // إذا لم نجد أي آية (نادر جداً)، نضع آية توحيدية عامة موثقة
  if (allVerses.length === 0) {
    allVerses.push({
      id: `${prophet.id}-fallback`,
      surah: 'الأنبياء',
      ayahNumber: '٩٠',
      text: 'إِنَّهُمْ كَانُوا يُسَارِعُونَ فِي الْخَيْرَاتِ وَيَدْعُونَنَا رَغَبًا وَرَهَبًا ۖ وَكَانُوا لَنَا خَاشِعِينَ',
      theme: 'صفات الأنبياء والقدوة الحسنة',
      chapterTitle: `سيرة نبي الله ${prophet.name}`,
      tafsirSource: 'تفسير السعدي',
      ageExplanations: {
        '5-7': {
          summary: `كان أنبياء الله الكرام يسارعون في عمل الخير ومساعدة الناس، ويدعون الله دائماً بحب وأدب.`,
          actionPoint: `سارع اليوم لعمل خير لطيف يسعد أسرتك.`,
          discussionQuestion: `ما هو الخير الذي تحب أن تعمله أول ما تستيقظ؟`
        },
        '8-10': {
          summary: `تثني الآية على الأنبياء بمسارعتهم في الطاعات ودعاء الله رجاءً لرحمته وخوفاً من معصيته مع كمال الخشوع.`,
          actionPoint: `لا تؤجل الصلاة أو عمل الخير، بل بادر إليه فوراً مثل الأنبياء الكرام.`,
          discussionQuestion: `ما أهمية المسارعة في الخيرات بدلاً من التردد أو الكسل؟`
        },
        '11-13': {
          summary: `منهج الأنبياء يقوم على الموازنة بين الرغبة والرهبة (الرجاء والخوف) المقرونة بالخشوع لله والمسارعة إلى كل بر.`,
          actionPoint: `اجعل دافعك في الطاعة حب الله والرغبة في جنته ورضوانه مع الحذر من مساخطه.`,
          discussionQuestion: `كيف يحقق المسلم التوازن النفسي والروحي بين الرجاء والخوف؟`,
          deeperTafsir: `بين المفسرون أن المسارعة تدل على شغف القلب بالطاعة، والخشوع هو سكون الجوارح وتواضع القلب لرب العالمين.`
        }
      }
    });
  }

  return allVerses;
}
